        public const uint TOKEN_QUERY = 0x0008;
        public const int TokenElevation = 20;
        public const uint WM_CLOSE = 0x0010;

        public static bool IsProcessElevated(uint processId)
        {
            if (processId == 0) return false;
            IntPtr processHandle = IntPtr.Zero;
            IntPtr tokenHandle = IntPtr.Zero;
            try
            {
                processHandle = OpenProcess(0x1000 /* PROCESS_QUERY_LIMITED_INFORMATION */, false, processId);
                if (processHandle == IntPtr.Zero) return false;
                if (!OpenProcessToken(processHandle, TOKEN_QUERY, out tokenHandle)) return false;
                if (!GetTokenInformation(tokenHandle, TokenElevation, out var elevation, Marshal.SizeOf<TOKEN_ELEVATION>(), out _)) return false;
                return elevation.TokenIsElevated != 0;
            }
            catch
            {
                return false;
            }
            finally
            {
                if (tokenHandle != IntPtr.Zero) CloseHandle(tokenHandle);
                if (processHandle != IntPtr.Zero) CloseHandle(processHandle);
            }
        }

